# equivalent to mouseDragged
# Note: Origin (0,0) sits in the top left corner
# Converts a fabric.js path (of the stroke) into the (x, y) format.
# Returns a list of (x, y) points
# streamlit returns a path of a line in an SVG path format,
# so these aren't exact mouse positions, but approximations
def get_points(path):
    points = []
    for c in path:
        if c[0] == 'M':                   # ["M", x, y] - Move to point
            points.append([c[1], c[2]])
        elif c[0] == 'Q':                 # ["Q", control_x, control_y, end_x, end_y], - Curve
            x, y = c[3], c[4]
            points.append([x, y])
        elif c[0] == 'L':                 # ["L", next_x, next_y]  - Line
            x, y = c[1], c[2]
            points.append([x, y])
    return points


# equivalent to mouseReleased
def on_new_line(raw_lines):
    if not len(raw_lines) > 0: # nothing drawn
        return

    model = ss.model

    raw_line_svg = raw_lines[-1] # newest stroke

    ss.user_lines.append(raw_line_svg)
    ss.object_count += 1

    # path of the entire line user drew
    path = raw_line_svg["path"] # its [["M", x, y], ["Q", ...], ...], etc.

    # list of raw points converted from streamlit's SVG path
    # raw_line_points is equivalent to currentRawLine in mouseReleased from JS
    raw_line = get_points(path) # [[x, y], [x, y], ...]

    ss.all_raw_lines.append(raw_line)

    raw_line_simplified = model.simplify_line(raw_line, 1.5)

    # the end point of previous line is needed
    prev_line_end_point = (0, 0)
    if len(ss.all_raw_lines) > 1:
        prev_line_end_point = ss.all_raw_lines[-2][-1]

    stroke = model.line_to_stroke(raw_line_simplified, prev_line_end_point)
    stroke.pop(0)

    ss.strokes = ss.strokes + stroke

    initRNNStateFromStrokes(ss.strokes)


@st.fragment(run_every=0.2)
def poll_camera():
    socket = ss.camera_socket
    size_changed = False
    for _ in range(256):
        try:
            message = json.loads(socket.recv(timeout=0))
        except TimeoutError:
            break
        except ConnectionClosed:
            disconnect_camera()
            st.rerun()

        if message.get("type") == "COMPLETE":
            ss.pop("current_camera_stroke", None)
            if ss.get("camera_strokes"):
                ss.camera_pending = True
                break
            continue

        if not message.get("pen_down"):
            ss.pop("current_camera_stroke", None)
            continue

        size = (message["width"], message["height"])
        if size != ss.get("camera_size"):
            restart()
            ss.camera_size = size
            size_changed = True

        if "current_camera_stroke" not in ss:
            ss.current_camera_stroke = []
            ss.setdefault("camera_strokes", []).append(ss.current_camera_stroke)
        ss.current_camera_stroke.append([message["x"], message["y"]])

    if size_changed or ss.get("camera_pending"):
        st.rerun()

    st.caption("Camera connected. Lift the pen to generate a continuation.")


width, height = CANVAS_WIDTH, CANVAS_HEIGHT
if source == "Camera":
    if ss.pop("camera_pending", False):
        ss.model_strokes = []
        paths = ss.model.simplify_lines(ss.camera_strokes, 1.5)
        ss.all_raw_lines = [
            path for path in paths if len(path) >= 2 and any(point != path[0] for point in path)
        ]
        if ss.all_raw_lines:
            ss.strokes = ss.model.lines_to_stroke(ss.all_raw_lines)[:-1]
            initRNNStateFromStrokes(ss.strokes, min_strokes=1)
            while ss.model_drawing:
                draw(update_canvas=False)
            if not any(
                previous[2] == 1 and (move[0] or move[1])
                for previous, move in zip(ss.model_strokes, ss.model_strokes[1:])
            ):
                ss.model_strokes = []

    if "camera_socket" in ss:
        poll_camera()
    if ss.all_raw_lines and not ss.model_strokes:
        st.info("No model lines to export. Draw another stroke.")
    width, height = ss.get("camera_size", (CANVAS_WIDTH, CANVAS_HEIGHT))
else:
    canvas_result = st_canvas(
        initial_drawing={"version": "4.4.0", "objects": ss.generated_lines + ss.user_lines},
        drawing_mode="freedraw",
        fill_color="rgba(255, 165, 0, 0.3)",
        stroke_width=2,
        stroke_color="#FF0000", # JS says that the user always draws in red
        background_color="#EEEEEE",
        update_streamlit=True,
        width=CANVAS_WIDTH,
        height=CANVAS_HEIGHT,
        return_image_data=True,
        key=f"canvas{ss.canvas_key}",
    )

    if canvas_result.json_data is not None:
        objects = canvas_result.json_data.get("objects", [])
        if len(objects) > ss.object_count:
            on_new_line(objects)
        if ss.model_drawing:
            draw()
            if ss.model_drawing:
                st.rerun()


