CANVAS_WIDTH = 700
CANVAS_HEIGHT = 400

# State (equivalent to the "let" variables from JS)
ss = st.session_state
ss.setdefault("canvas_key", 0)                    # increase to get a fresh, empty canvas
ss.setdefault("temperature", 0.25)
ss.setdefault("all_raw_lines", [])                 # contains lines in form of lists of points: list([x, y]), !! not deltas
ss.setdefault("strokes", [])                       # contains all the strokes [dx, dy, p1, p2, p3]]
ss.setdefault("object_count", 0)                   # canvas objs already converted to strokes

ss.setdefault("x", 0)
ss.setdefault("y", 0)
ss.setdefault("dx", 0)
ss.setdefault("dy", 0)
ss.setdefault("model_state", None)
ss.setdefault("model_drawing", False)
ss.setdefault("prev_pen_state", [0, 1, 0]) # previous pen state [pen_down, pen_up, end]

# lines generated by the model
ss.setdefault("generated_lines", [])
# lines generated by the user
ss.setdefault("user_lines", [])

ss.setdefault("model_strokes_count", 0)

# the model's latest turn, for the plotter
ss.setdefault("model_strokes", [])     # [dx, dy, p1, p2, p3] in canvas pixels
ss.setdefault("model_anchor", (0, 0))  # canvas point the first delta starts from

# Update Functions
def restart():
    ss.canvas_key += 1 # new key results in a new empty canvas
    ss.object_count = 0

    ss.user_lines = []
    ss.generated_lines = []

    ss.all_raw_lines = []
    ss.strokes = []

    ss.prev_pen_state = [0, 1, 0]

    ss.model_state = None
    ss.model_strokes = []

# Layout (UI and DOM elements)
st.title("Pen Pal Canvas")
st.subheader("Interactive Sketch Prediction")
st.write("This demo attempts to finish the drawing of a cat, given whatever strokes you draw on the screen.")

col1, col2 = st.columns(2, vertical_alignment="bottom")

with col1:
    st.button("Clear", on_click=restart, use_container_width=True)
with col2:
    st.slider(
        "Temperature",
        min_value=0.0,
        max_value=1.0,
        step=0.05,
        key="temperature")

canvas_result = st_canvas(
    initial_drawing={"version": "4.4.0", "objects": ss.generated_lines + ss.user_lines},
    drawing_mode="freedraw",
    fill_color="rgba(255, 165, 0, 0.3)",  
    stroke_width=2,
    stroke_color="#FF0000", # JS says that the user always draws in red
    background_color="#EEEEEE",
    update_streamlit=True,
    width=CANVAS_WIDTH,
    height=CANVAS_HEIGHT,
    return_image_data=True,
    key=f"canvas{ss.canvas_key}",
)


# load model once when streamlit program starts:
if "model" not in ss:
    ss.model = load_model()
    ss.model_state = ss.model.zeroState()


# equivalent to mouseDragged
# Note: Origin (0,0) sits in the top left corner
# Converts a fabric.js path (of the stroke) into the (x, y) format.
# Returns a list of (x, y) points
# streamlit returns a path of a line in an SVG path format,
# so these aren't exact mouse positions, but approximations
def get_points(path):
    points = []
    for c in path:
        if c[0] == 'M':                   # ["M", x, y] - Move to point
            points.append([c[1], c[2]])
        elif c[0] == 'Q':                 # ["Q", control_x, control_y, end_x, end_y], - Curve
            x, y = c[3], c[4]
            points.append([x, y])
        elif c[0] == 'L':                 # ["L", next_x, next_y]  - Line
            x, y = c[1], c[2]
            points.append([x, y])
    return points


# equivalent to mouseReleased
def on_new_line(raw_lines):
    if not len(raw_lines) > 0: # nothing drawn
        return

    model = ss.model

    raw_line_svg = raw_lines[-1] # newest stroke

    ss.user_lines.append(raw_line_svg)
    ss.object_count += 1

    # path of the entire line user drew
    path = raw_line_svg["path"] # its [["M", x, y], ["Q", ...], ...], etc.

    # list of raw points converted from streamlit's SVG path
    # raw_line_points is equivalent to currentRawLine in mouseReleased from JS
    raw_line = get_points(path) # [[x, y], [x, y], ...]

    ss.all_raw_lines.append(raw_line)

    raw_line_simplified = model.simplify_line(raw_line, 2)

    # the end point of previous line is needed
    prev_line_end_point = (0, 0)
    if len(ss.all_raw_lines) > 1:
        prev_line_end_point = ss.all_raw_lines[-2][-1]

    stroke = model.line_to_stroke(raw_line_simplified, prev_line_end_point)
    stroke.pop(0)

    strokes = ss.strokes + stroke

    initRNNStateFromStrokes(strokes)



# this is called whenever a new stroke was drawn
if canvas_result.json_data is not None:
    objects = canvas_result.json_data.get("objects", [])

    # more strokes than previous drawing
    if len(objects) > ss.object_count:
        on_new_line(objects)
    elif ss.model_drawing:
        draw()


# Plotter preview: what the plotter would draw for the model's latest turn.
# Only reached while the model is idle, because draw() reruns the script after every step.
if ss.model_strokes:
    st.subheader("Plotter preview")
    to_paper = CanvasToPaper(CANVAS_WIDTH, CANVAS_HEIGHT)
    gcode = strokes_to_gcode(to_paper.strokes(ss.model_strokes), to_paper.point(*ss.model_anchor),
                             max_steps=len(ss.model_strokes))
    sim = simulate(gcode)
    human = [[to_paper.point(x, y) for x, y in line] for line in ss.all_raw_lines]

    out = ROOT / "plotter" / "output" / "latest.gcode"
    out.parent.mkdir(exist_ok=True)
    write_gcode(gcode, out)

    st.pyplot(render(sim, overlay=human))
    st.caption(summary(sim) + f" Saved to {out.relative_to(ROOT)}")
    for w in sim["warnings"]:
        st.warning(w)

    dl_col, send_col = st.columns(2)
    dl_col.download_button("Download G-code", "\n".join(gcode) + "\n", file_name="penpal.gcode")
    dry_run = st.checkbox("Practice run (pretend Arduino)", key="plot_dry_run")
    if send_col.button("Send to plotter", key="send_plotter", disabled=bool(sim["warnings"])):
        bar = st.progress(0.0, "Connecting to the plotter...")

        def show_progress(i, n, line):
            bar.progress(i / n, f"Plotting: line {i} of {n}")

        try:
            send_gcode(gcode, ser=FakeGrbl() if dry_run else None, on_progress=show_progress)
            st.success("Practice run done." if dry_run else "Done. The pen should be back at the home corner.")
        except PlotterError as e:
            st.error(str(e))
