# Update Functions
def restart():
    ss.canvas_key += 1 # new key results in a new empty canvas
    ss.object_count = 0

    ss.user_lines = []
    ss.generated_lines = []

    ss.all_raw_lines = []
    ss.strokes = []

    ss.prev_pen_state = [0, 1, 0]

    ss.model_state = None
    ss.model_drawing = False
    ss.model_strokes_count = 0
    ss.model_strokes = []
    ss.pop("camera_size", None)
    ss.pop("camera_strokes", None)
    ss.pop("current_camera_stroke", None)
    ss.pop("camera_pending", None)


def disconnect_camera():
    socket = ss.pop("camera_socket", None)
    if socket is not None:
        socket.close()
    ss.pop("current_camera_stroke", None)


def change_source():
    disconnect_camera()
    restart()


def connect_camera():
    try:
        ss.camera_socket = connect(CAMERA_URL, open_timeout=1, close_timeout=1)
    except (OSError, TimeoutError, WebSocketException):
        st.error("Could not connect. Start the camera server with python CV/server.py.")


